#!/usr/bin/env python3
"""Writes resources/ml/requirements-base.lock and requirements-torch.lock: every package the ML environment installs
(the pinned ones and everything they pull in), each with the sha256 of every wheel PyPI publishes for that version.

pip then installs with --require-hashes: a wheel whose bytes differ from the ones listed (a compromised mirror, a
replaced file) is refused, and so is any package that is not in the file. One file serves every platform: pip picks
the wheel for this computer and checks its hash among those listed.

Run it after changing a version in PINS (then build: the files are app resources):
    python3 tools/ml_lock.py
The dependency lists below were read from the installed packages' metadata (macOS and Windows markers; Linux, where
xgboost and torch pull CUDA packages, is not a Deepwater platform) — check them again when a version changes.
"""
import hashlib
import json
import os
import sys
import urllib.request

# name -> version. "base": AI › ML's INSTALL; "torch": INSTALL PYTORCH (self-supervised learning), on top of base.
PINS = {
    "base": {
        # asked for (ml::Environment::requirements)
        "numpy": "2.5.5", "pandas": "3.1.1", "scipy": "1.18.1", "scikit-learn": "1.9.1", "joblib": "1.6.0",
        "lightgbm": "4.7.0", "xgboost": "3.4.1",
        # pulled in: pandas -> python-dateutil -> tzdata; scikit-learn, lightgbm -> narwhals; scikit-learn ->
        # threadpoolctl; joblib -> cloudpickle
        "python-dateutil": "4.0.0", "tzdata": "2026.6", "narwhals": "2.28.0", "threadpoolctl": "3.8.0",
        "cloudpickle": "3.1.2",
    },
    "torch": {
        "torch": "2.15.0",
        # torch -> filelock, fsspec, jinja2 (-> markupsafe), networkx, setuptools, sympy (-> mpmath), typing-extensions
        "filelock": "4.2.10", "fsspec": "2026.9.0", "jinja2": "3.1.6", "markupsafe": "3.0.4", "networkx": "3.7",
        "setuptools": "84.2.1", "sympy": "1.14.0", "mpmath": "1.3.0", "typing-extensions": "4.16.0",
    },
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def wheels(name, version):
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    req = urllib.request.Request(url, headers={"User-Agent": "deepwater-ml-lock"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = json.load(r)
    out = sorted({u["digests"]["sha256"] for u in data["urls"] if u["packagetype"] == "bdist_wheel" and not u.get("yanked")})
    if not out:
        sys.exit(f"{name}=={version}: no wheel on PyPI (the install takes binary wheels only)")
    return out


def main():
    for group, pins in PINS.items():
        lines = [f"# Generated by tools/ml_lock.py — do not edit by hand. {group}: pip install --require-hashes -r this file"]
        for name in sorted(pins):
            hashes = wheels(name, pins[name])
            lines.append(f"{name}=={pins[name]} \\")
            lines += [f"    --hash=sha256:{h}" + (" \\" if i + 1 < len(hashes) else "") for i, h in enumerate(hashes)]
            print(f"{group}: {name}=={pins[name]}: {len(hashes)} wheel(s)")
        path = os.path.join(ROOT, "resources", "ml", f"requirements-{group}.lock")
        with open(path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote", os.path.relpath(path, ROOT), hashlib.sha256(open(path, "rb").read()).hexdigest()[:12])


if __name__ == "__main__":
    main()
